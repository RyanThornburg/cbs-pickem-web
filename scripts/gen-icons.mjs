// Writes src/dashboard/ui/iconData.ts: the SVG shapes of every
// @mui/icons-material icon the app imports, so ui/Icon can draw them
// without MUI. Re-run after importing a new MUI icon somewhere:
//
//   node scripts/gen-icons.mjs [ExtraIconName ...]
//
// The shapes are Google's Material icons (Apache 2.0), as MUI ships them.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const require = createRequire(join(ROOT, "package.json"));
const { createElement } = require("react");
const { renderToStaticMarkup } = require("react-dom/server");

const sources = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else if (/\.tsx?$/.test(name)) sources.push(readFileSync(path, "utf8"));
  }
};
walk(join(ROOT, "src"));

// Icons already moved to ui/icons are listed there; keep them too.
const existing = (() => {
  try {
    return [
      ...readFileSync(
        join(ROOT, "src/dashboard/ui/iconData.ts"),
        "utf8"
      ).matchAll(/^ {2}(\w+): \[/gm),
    ].map((m) => m[1]);
  } catch {
    return [];
  }
})();
const names = new Set(existing);
// Extra names on the command line, for icons MUI drew from its own
// internals rather than an import (TableSortLabel's ArrowDownward).
for (const name of process.argv.slice(2)) names.add(name);
for (const source of sources) {
  for (const m of source.matchAll(/from "@mui\/icons-material\/(\w+)"/g)) {
    names.add(m[1]);
  }
}

const camel = (attr) => attr.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const entries = [...names].sort().map((name) => {
  const Icon = require(`@mui/icons-material/${name}`).default;
  const svg = renderToStaticMarkup(createElement(Icon));
  // Emotion puts a <style> tag first when rendering on the server.
  const inner = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/)[1];
  const shapes = [...inner.matchAll(/<(\w+)([^>]*?)\/?>/g)].map(
    ([, tag, attrs]) => [
      tag,
      Object.fromEntries(
        [...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, k, v]) => [
          camel(k),
          v,
        ])
      ),
    ]
  );
  return `  ${name}: ${JSON.stringify(shapes)},`;
});

writeFileSync(
  join(ROOT, "src/dashboard/ui/iconData.ts"),
  `// Generated by scripts/gen-icons.mjs from @mui/icons-material (Material
// icons, Apache 2.0). Each icon is a list of [tag, attributes] on a 24x24
// viewBox. Don't edit by hand; re-run the script.
export const ICONS = {
${entries.join("\n")}
} as const satisfies Record<string, ReadonlyArray<readonly [string, Record<string, string>]>>;

export type IconName = keyof typeof ICONS;
`
);
console.log(`Wrote ${entries.length} icons.`);
